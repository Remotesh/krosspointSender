/**
 * Small shared helpers for the converters and the EPUB builder.
 * These are internal. The public API is in index.ts.
 */
import type { Article, FilenameRules } from '../types';

export const XHTML_NS = 'http://www.w3.org/1999/xhtml';
export const EPUB_NS = 'http://www.idpf.org/2007/ops';
export const XMLNS_NS = 'http://www.w3.org/2000/xmlns/';
export const XML_NS = 'http://www.w3.org/XML/1998/namespace';

export const APP_NAME = 'K-rosspointSender';

export const DEFAULT_FILENAME_RULES: FilenameRules = {
  template: '{title}',
  maxLength: 80,
  lowercase: false,
  spaceReplacement: '',
};

// XML 1.0 allows only these characters. We remove all others.
const INVALID_XML_CHARS = /[^\u0009\u000A\u000D\u0020-\uD7FF\uE000-\uFFFD\u{10000}-\u{10FFFF}]/gu;

/** Removes characters that XML 1.0 does not allow. */
export function cleanXmlText(s: string): string {
  return s.replace(INVALID_XML_CHARS, '');
}

/** Escapes text for XML element content and attribute values. */
export function escapeXml(s: string): string {
  return cleanXmlText(s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

/** Collapses all whitespace runs to one space and trims. It also removes characters that XML does not allow. */
export function collapseWs(s: string): string {
  return cleanXmlText(s).replace(/\s+/g, ' ').trim();
}

/** Returns YYYY-MM-DD for an ISO date. Returns '' when the date is not valid. */
export function isoDay(iso?: string): string {
  if (!iso) return '';
  const m = /^(\d{4}-\d{2}-\d{2})/.exec(iso);
  if (m) return m[1];
  const d = new Date(iso);
  return Number.isNaN(d.getTime()) ? '' : d.toISOString().slice(0, 10);
}

/** Returns a timestamp in the form CCYY-MM-DDThh:mm:ssZ (EPUB dcterms:modified). */
export function modifiedStamp(d = new Date()): string {
  return d.toISOString().replace(/\.\d{3}Z$/, 'Z');
}

/** Returns a valid BCP47-like language tag. The default is "en". */
export function langOf(article: Pick<Article, 'language'>): string {
  const l = (article.language ?? '').trim();
  return /^[A-Za-z]{2,3}(-[A-Za-z0-9]{1,8})*$/.test(l) ? l : 'en';
}

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/** Returns a random v4 UUID. It uses crypto.randomUUID when the browser has it. */
export function randomUuid(): string {
  const c = (globalThis as { crypto?: Crypto }).crypto;
  if (c && typeof c.randomUUID === 'function') return c.randomUUID();
  const b = new Uint8Array(16);
  if (c && typeof c.getRandomValues === 'function') c.getRandomValues(b);
  else for (let i = 0; i < 16; i++) b[i] = Math.floor(Math.random() * 256);
  b[6] = (b[6] & 0x0f) | 0x40;
  b[8] = (b[8] & 0x3f) | 0x80;
  const h = Array.from(b, (x) => x.toString(16).padStart(2, '0')).join('');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
}

/** Returns "urn:uuid:<id>". It uses the article id when it is a UUID, so a re-export keeps the same identity. */
export function bookIdentifier(id?: string): string {
  return `urn:uuid:${id && UUID_RE.test(id) ? id.toLowerCase() : randomUuid()}`;
}

/** Pads a number with zeros. */
export function pad(n: number, width: number): string {
  return String(n).padStart(width, '0');
}

/** Counts whitespace-separated words in a text. */
export function countTextWords(text: string): number {
  const t = text.trim();
  return t ? t.split(/\s+/).length : 0;
}

/** Reads a Blob as bytes. It works with Blob.arrayBuffer and with FileReader. */
export async function blobToBytes(blob: Blob): Promise<Uint8Array> {
  if (typeof blob.arrayBuffer === 'function') {
    return new Uint8Array(await blob.arrayBuffer());
  }
  return new Promise((resolve, reject) => {
    const r = new FileReader();
    r.onload = () => resolve(new Uint8Array(r.result as ArrayBuffer));
    r.onerror = () => reject(r.error);
    r.readAsArrayBuffer(blob);
  });
}

/** Makes a Blob from bytes. The copy makes sure the buffer is a plain ArrayBuffer. */
export function bytesToBlob(bytes: Uint8Array, type: string): Blob {
  const copy = new Uint8Array(bytes.byteLength);
  copy.set(bytes);
  return new Blob([copy.buffer], { type });
}

/** The text of the source note: "Source: <url>, captured <date>, generated by K-rosspointSender." */
export function sourceNoteText(article: Article): string {
  const src = article.sourceUrl?.trim() || `${article.inputKind} input`;
  const day = isoDay(article.capturedAt) || isoDay(new Date().toISOString());
  return `Source: ${src}, captured ${day}, generated by ${APP_NAME}.`;
}

/** Label/value lines for the title page. Empty values are left out. */
export function coverLines(article: Article): { label: string; value: string }[] {
  const lines: { label: string; value: string }[] = [];
  const add = (label: string, value?: string) => {
    const v = collapseWs(value ?? '');
    if (v) lines.push({ label, value: v });
  };
  add('Author', article.author);
  add('Site', article.siteName);
  add('Published', isoDay(article.publishedAt));
  add('Source', article.sourceUrl);
  add('Captured', isoDay(article.capturedAt));
  if (article.wordCount > 0) add('Words', article.wordCount.toLocaleString('en-US'));
  return lines;
}
